#!/usr/bin/env python3
"""Build a DO initialization sample manifest from vortex checkpoint files.

Default behavior:
- scan ../output/casefile_*.chk
- choose up to --max-files snapshots uniformly in index
- write manifest (one path per line) to do_init_samples.txt
"""

from __future__ import annotations

import argparse
import os
import re
from pathlib import Path


def _chk_index(path: Path) -> int:
    m = re.search(r"_(\d+)\.chk$", path.name)
    return int(m.group(1)) if m else -1


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--output-dir",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "output",
        help="Directory containing casefile_*.chk",
    )
    ap.add_argument(
        "--pattern",
        default="casefile_*.chk",
        help="Glob pattern for sample checkpoint files",
    )
    ap.add_argument(
        "--max-files",
        type=int,
        default=40,
        help="Maximum number of samples listed in manifest",
    )
    ap.add_argument(
        "--manifest",
        type=Path,
        default=Path(__file__).resolve().parent / "do_init_samples.txt",
        help="Output manifest path",
    )
    args = ap.parse_args()

    if args.max_files <= 0:
        raise ValueError("--max-files must be > 0")

    files = sorted(args.output_dir.glob(args.pattern), key=_chk_index)
    if not files:
        raise RuntimeError(
            f"No files matched {args.pattern!r} in {args.output_dir}. "
            "Run a deterministic/sampling stage first to produce checkpoints."
        )

    n = min(args.max_files, len(files))
    if n < len(files):
        idx = [round(i * (len(files) - 1) / (n - 1)) for i in range(n)] if n > 1 else [0]
        selected = [files[i] for i in idx]
    else:
        selected = files

    args.manifest.parent.mkdir(parents=True, exist_ok=True)
    with args.manifest.open("w", encoding="utf-8") as f:
        f.write("# DO init sample checkpoints for cases/vortex\n")
        f.write("# Generated by ic/build_do_sample_manifest.py\n")
        for p in selected:
            # Keep paths relative to the manifest directory for portability.
            rel = os.path.relpath(
                p.resolve(), start=args.manifest.parent.resolve()
            )
            f.write(f"{Path(rel).as_posix()}\n")

    print(f"Wrote {len(selected)} samples to {args.manifest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
